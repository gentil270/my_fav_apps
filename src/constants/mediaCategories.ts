export const CATEGORY_MAP = new Map(MEDIA_CATEGORIES.map((c) => [c.id, c]));

export function mapIptvCategoryToMediaCategory(rawCat?: string): string {
  const normalized = (rawCat || 'general').toLowerCase().trim();
  for (const cat of MEDIA_CATEGORIES) {
    if (cat.id !== 'all' && cat.tvCategories.includes(normalized)) {
      return cat.id;
    }
  }
  return 'entertainment';
}

